// 메인 창 크기 (ADR-093). Electron에 의존하지 않아 화면 e2e · 단위 시험이 같은 값을 읽는다.
// - 기본 크기 1280 × 800은 창 바깥 크기다(테두리 · 제목 줄 포함, 이전과 같음).
// - 최소 크기는 창 안쪽(웹 페이지) 크기다. 화면 정의서는 최소 창 크기를 정하지 않았고 SCR-21 설정 모달을 820 × 600으로
//   정했다. 채팅이 44px 띠로 접힌 창의 목록 · 상세 배치는 784px(사이드바 232 + 목록 최소 220 + 상세 최소 288 + 띠 44,
//   ADR-090) 이상이면 가로 스크롤이 없으므로, 둘 다 지키는 820 × 600을 최소로 둔다.

/** 기본 창 크기 (바깥 크기) */
export const DEFAULT_WINDOW_SIZE = { width: 1280, height: 800 } as const;

/** 최소 창 크기 (안쪽 크기): 설정 모달(SCR-21) 820 × 600이 줄지 않고 들어가는 크기 */
export const MIN_CONTENT_SIZE = { width: 820, height: 600 } as const;
