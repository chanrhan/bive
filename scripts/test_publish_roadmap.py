pr = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(pr)

REPO = "o/r"
MS_TITLE = "M9 시험"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
CRITERIA = "기준 하나 · 기준 둘"


def roadmap(rows, criteria=CRITERIA):
    """rows: [(키, 제목, 이슈 열)] -> 최소 로드맵 문서."""
    lines = [
        "# 로드맵", "", "## 2. 마일스톤", "", f"### 2.1 {MS_TITLE}", "",
        "**목표**: 시험용.", "", "**범위 밖**: 없음.", "",
        "| 키 | 제목 | 유형 | 영역 | 의존 | 수용 기준 | 관련 ID | 이슈 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for key, title, issue in rows:
        lines.append(f"| {key} | {title} | chore | ci | — | {criteria} | ADR-015 | {issue} |")
    lines += ["", "## 3. 커버리지", ""]
    return "\n".join(lines)


def row_body(key, title, criteria=("기준 하나", "기준 둘")):
    it = {"key": key, "title": title, "deps": [], "criteria": list(criteria), "ids": "ADR-015"}
    return pr.issue_body(it, {})


class FakeGitHub:
    """라벨 · 마일스톤은 이미 있고, 이슈 목록만 사례마다 다르다. 모든 호출을 calls에 남긴다.
    lookup은 번호로 하나를 GET할 때의 응답(마일스톤 밖 이슈 · 풀 리퀘스트)."""

    def __init__(self, issues, lookup=None):
        self.issues = issues
        self.lookup = lookup or {}
        self.calls = []
        self.next_number = 1000

    def listing(self, path):
        if path == f"repos/{REPO}/labels":
            return [{"name": n} for n, _ in pr.LABELS]
        if path == f"repos/{REPO}/milestones?state=all":
            return [{"title": MS_TITLE, "number": 9}]
        if path == f"repos/{REPO}/issues?state=all&milestone=9":
            return [dict(i) for i in self.issues]
        raise AssertionError(f"예상하지 않은 목록 호출: {path}")

    def gh_list(self, path):
        self.calls.append(("GET", path))
        return self.listing(path)

    def gh(self, method, path, payload=None, extra=()):
        self.calls.append((method, path, tuple(extra)))
        if method == "GET":
            m = re.fullmatch(r"(.*)[?&]per_page=(\d+)&page=(\d+)", path)
            if m:  # 실제 gh_list가 부르는 페이지 하나
                per, page = int(m.group(2)), int(m.group(3))
                items = self.listing(m.group(1))[(page - 1) * per:page * per]
                return "".join(json.dumps(i, ensure_ascii=False) + "\n" for i in items)
            m = re.fullmatch(rf"repos/{REPO}/issues/(\d+)", path)
            if m:
                n = int(m.group(1))
                if n not in self.lookup:
                    raise pr.GhError("gh: Not Found (HTTP 404)")
                return json.dumps(self.lookup[n])
        if method == "POST" and path == f"repos/{REPO}/issues":
            self.next_number += 1
            self.issues.append({"number": self.next_number, "title": payload["title"],
                                "state": "open", "body": payload["body"]})
            return json.dumps({"number": self.next_number})
        if method == "PATCH":
            n = int(path.rsplit("/", 1)[1])
            next(i for i in self.issues if i["number"] == n)["body"] = payload["body"]
            self.patch_bodies.append(payload["body"])
            return "{}"
        raise AssertionError(f"예상하지 않은 호출: {method} {path}")

    patch_bodies = None

    def writes(self):
        return [c for c in self.calls if c[0] != "GET"]

    def created(self):
        return [c[:2] for c in self.calls if c[0] == "POST"]

    def patched(self):
        return [c[:2] for c in self.calls if c[0] == "PATCH"]


def issue(number, title, state="closed", body="", reason=None):
    return {"number": number, "title": title, "state": state, "body": body,
            "state_reason": reason or ("completed" if state == "closed" else None)}


class PublishRoadmapTest(unittest.TestCase):
    def run_main(self, fake, rows, *flags, criteria=CRITERIA, real_list=False):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        path = Path(tmp.name) / "roadmap.md"
        path.write_text(roadmap(rows, criteria), encoding="utf-8")
        fake.patch_bodies = []
        out = io.StringIO()
        argv = ["publish-roadmap.py", "--repo", REPO, "--roadmap", str(path), *flags]
        patches = [mock.patch.object(pr, "gh", fake.gh), mock.patch.object(sys, "argv", argv)]
        if not real_list:
            patches.append(mock.patch.object(pr, "gh_list", fake.gh_list))
        for p in patches:
            p.start()
            self.addCleanup(p.stop)
        with redirect_stdout(out):
            code = pr.main()
        return code, out.getvalue(), path.read_text(encoding="utf-8")

